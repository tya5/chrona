"""The #806 additive syntax stays a pure compiler input and preserves legacy output."""
from __future__ import annotations

import pytest

from chrona.resources import safe_load
from chrona.terse import CODES, compile_terse, emit_project, locate


def test_declared_extensions_profiles_and_fields_map_to_project_constructs():
    text = ('project p "Plan" extension tags "packages/tags.yaml" abc123\n'
            'a "A" task profile risk-profile 2d deadline 2027-03-05 risk=high note="two words" '
            'flag="true" enabled=true count=2 ratio=1.25 empty=null\n'
            'b group profile group-profile\n')
    result = compile_terse(text)
    assert result.ok
    assert result.profile_bindings == ("a", "b")
    assert result.project["extensions"] == [{"packageId": "tags", "path": "packages/tags.yaml", "revision": "abc123"}]
    obj = result.project["objects"]["a"]
    assert obj == {"type": "risk-profile", "title": "A", "schedule": {"mode": "scheduled", "amount": "2d"},
                   "deadline": "2027-03-05", "fields": {"risk": "high", "note": "two words", "flag": "true",
                   "enabled": True, "count": 2, "ratio": 1.25, "empty": None}}
    assert result.source_map["/objects/a/type"] == locate(result.source_map, "/objects/a/type")
    assert result.source_map["/objects/a/type"].column == text.splitlines()[1].index("risk-profile") + 1
    assignment = text.splitlines()[1].index('note="two words"') + 1
    note_range = locate(result.source_map, "/objects/a/fields/note")
    assert (note_range.column, note_range.end_column) == (assignment, assignment + len('note="two words"'))
    assert safe_load(emit_project(result.project)) == result.project


def test_field_source_map_uses_json_pointer_escaping():
    result = compile_terse('project p\na task profile custom 1d a/b~c=value\n')
    assert result.ok
    assert "/objects/a/fields/a~1b~0c" in result.source_map
    assert "/objects/a/fields/a/b~c" not in result.source_map


def test_missing_required_field_context_points_at_the_explicit_profile():
    result = compile_terse("project p\na task profile custom 1d\n")
    assert result.ok
    assert result.source_map["/objects/a/fields"].column == 16


@pytest.mark.parametrize(("value", "expected"), [
    ("true", True), ("false", False), ("null", None), ("0", 0), ("-0", 0),
    ("2.50", 2.5), ("1e3", 1000.0), ("1e-5", 1e-5), ("1e20", 1e20),
    ('"2"', "2"), ('"false"', "false"), ('""', ""),
    ("2027-03-05", "2027-03-05"), ("not-json", "not-json"),
])
def test_field_scalar_grammar_is_json_without_yaml_implicit_coercion(value, expected):
    result = compile_terse(f"project p\na task profile custom 1d field={value}\n")
    assert result.ok and result.project["objects"]["a"]["fields"]["field"] == expected
    assert safe_load(emit_project(result.project)) == result.project


@pytest.mark.parametrize("value", ["NaN", "Infinity", "-Infinity", "1e999"])
def test_nonfinite_numbers_are_positioned_field_value_errors(value):
    result = compile_terse(f"project p\na task profile custom 1d field={value}\n")
    assert not result.ok and [(item.id, item.range.line) for item in result.diagnostics] == [("E_TERSE_FIELD_VALUE", 2)]


@pytest.mark.parametrize(("tail", "code"), [
    ("=value", "E_TERSE_FIELD_KEY"), ("field=", "E_TERSE_FIELD_VALUE"),
    ("field=value field=again", "E_TERSE_CLAUSE_DUPLICATE"),
    ("field=value", "E_TERSE_PROFILE_REQUIRED"),
])
def test_invalid_assignments_fail_without_a_partial_project(tail, code):
    profile = "" if code == "E_TERSE_PROFILE_REQUIRED" else " profile custom"
    result = compile_terse(f"project p\na task{profile} 1d {tail}\n")
    assert result.project is None and result.diagnostics[0].id == code


def test_explicit_profile_is_immediately_after_kind_and_profile_does_not_become_a_reserved_name():
    result = compile_terse("project p\nprofile task 1d\na task 1d profile custom\n")
    assert result.project is None
    assert result.diagnostics[0].id == "E_TERSE_TOKEN_UNEXPECTED"
    legacy = compile_terse("project p\nprofile task 1d\n")
    assert legacy.ok and legacy.profile_bindings == ()


def test_project_extension_package_ids_must_be_unique_on_the_declaration_line():
    result = compile_terse('project p extension tags "a.yaml" rev1 extension tags "b.yaml" rev2\n')
    assert result.project is None
    assert result.diagnostics[0].id == "E_TERSE_CLAUSE_DUPLICATE"


def test_legacy_project_output_and_result_default_remain_unchanged():
    result = compile_terse("project p\na task 1d\n")
    assert result.ok and result.profile_bindings == ()
    assert emit_project(result.project) == (
        "# generated by chrona compile (terse 0.1); once edited, this file is the authority\n"
        "version: timeline/v0.7\nproject:\n  id: p\nobjects:\n  a:\n    type: task\n    schedule: {mode: scheduled, amount: 1d}\n")


def test_application_unknown_profile_code_is_not_fabricated_by_the_pure_compiler():
    assert "E_TERSE_PROFILE_UNKNOWN" in CODES
    result = compile_terse("project p\na task profile not-checked 1d\n")
    assert result.ok and result.profile_bindings == ("a",)
    assert result.project["objects"]["a"]["type"] == "not-checked"
