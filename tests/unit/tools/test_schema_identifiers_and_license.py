def _category(node: dict[str, Any]) -> str:
    shape = {key: value for key, value in node.items() if key not in {"description", "examples"}}
    if shape == {"$ref": f"{COMMON_ID}#/$defs/identifier"}:
        return "identifier"
    if shape == {"type": "string", "minLength": 1}:
        return "non-empty-string"
    if shape == {"type": "string"}:
        return "unconstrained-string"
    if shape == {"type": "string", "minLength": 1, "maxLength": 4096}:
        return "bounded-non-empty-string"
    if shape == {"$ref": "#/$defs/id"}:
        return "layout-profile-id"
    if shape == {"$ref": "#/$defs/figureIdentity"}:
        return "figure-identity"
    if shape == {"$ref": f"{COMMON_ID}#/$defs/slug"}:
        return "slug"
    if shape in ({"$ref": f"{COMMON_ID}#/$defs/portableName"}, {"$ref": "#/$defs/name"}):
        return "portable-name"
    if shape == {"$ref": f"{COMMON_ID}#/$defs/storeAddress", "pattern": "^[^/]+$"}:
        return "store-segment"
    if shape in ({"$ref": "#/$defs/string"}, {"$ref": "#/$defs/text"}):
        return "scene-text"
    return "UNCLASSIFIED"


def _id_sites(name: str) -> list[tuple[str, str]]:
    return [(key, _category(value)) for node in _walk(_schema(name))
            if isinstance(node, dict) and isinstance(node.get("properties"), dict)
            for key, value in node["properties"].items() if key == "id" or key.endswith("Id")]


def _all_sites() -> Counter[tuple[str, str]]:
    counts: Counter[tuple[str, str]] = Counter()
    for name in LIVE:
        if name not in PARTS:
            counts.update((name, category) for _, category in _id_sites(name))
    return counts


def test_every_live_id_site_references_identifier_or_is_on_the_documented_allowlist():
    counts = _all_sites()
    assert not [key for key in counts if key[1] == "UNCLASSIFIED"], sorted(key for key in counts if key[1] == "UNCLASSIFIED")
    unaccounted = {key: n for key, n in counts.items() if key[1] != "identifier" and key not in ID_SITES}
    assert unaccounted == {}, "a new id site needs a category or a reference to `identifier`"
    assert {key: n for key, n in counts.items() if key[1] != "identifier"} == ID_SITES


def test_every_allowlisted_category_has_a_recorded_reason_and_no_entry_is_stale():
    assert {category for _, category in ID_SITES} <= set(ALLOWED_SHAPES)
    assert set(ALLOWED_SHAPES) == {category for _, category in ID_SITES}, "a reason without a site is stale"
    assert all(len(reason) > 40 for reason in ALLOWED_SHAPES.values())


