# S4d: license (B7). The asset schemas share `license`; color-scheme stays free text.
# --------------------------------------------------------------------------------------------

COLOR_SCHEME = "color-scheme-v0.2.schema.yaml"


def _scheme(license_value: Any) -> dict[str, Any]:
    document = yaml.safe_load((ROOT / "examples/aster-ssd/schemes/executive-light.yaml").read_bytes())
    document["body"]["provenance"]["license"] = license_value
    return document


@pytest.mark.parametrize("value", ["project-pending", "MIT", "CC-BY-4.0, attribution required", "Apache-2.0 WITH LLVM-exception", " free text "])
def test_color_scheme_license_stays_free_text(value):
    assert validator_for_schema(_schema(COLOR_SCHEME)).is_valid(_scheme(value))


@pytest.mark.parametrize("value", ["", 5, None, {"spdx": "MIT", "notice": "n"}, ["MIT"]])
def test_color_scheme_license_is_still_a_non_empty_string(value):
    assert not validator_for_schema(_schema(COLOR_SCHEME)).is_valid(_scheme(value))


def test_committed_schemes_keep_their_project_pending_license():
    declared = {path: yaml.safe_load(path.read_bytes())["body"]["provenance"]["license"]
                for path in sorted((ROOT / "examples").glob("*/schemes/*.yaml"))}
    assert "project-pending" in declared.values()
    validator = validator_for_schema(_schema(COLOR_SCHEME))
    for path in declared:
        assert validator.is_valid(yaml.safe_load(path.read_bytes())), path


def test_the_asset_schemas_share_the_license_object_and_color_scheme_does_not():
    assert COMMON_ID + "#/$defs/license" in (SCHEMAS / "icon-catalog-v0.5.schema.yaml").read_text(encoding="utf-8")
    assert COMMON_ID + "#/$defs/license" in (SCHEMAS / "theme-asset-source-v0.2.schema.yaml").read_text(encoding="utf-8")
    assert "common-v0.1#/$defs/license" not in (SCHEMAS / COLOR_SCHEME).read_text(encoding="utf-8")
    license_field = next(node["properties"]["license"] for node in _walk(_schema(COLOR_SCHEME))
                         if isinstance(node, dict) and isinstance(node.get("properties"), dict) and "license" in node["properties"])
    assert license_field["type"] == "string" and license_field["minLength"] == 1
    assert "free text" in license_field["description"]
